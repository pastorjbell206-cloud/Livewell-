#!/usr/bin/env node
/**
 * scan-citations.mjs — the citation-integrity worklist (Next-Ten #2).
 *
 * The corpus audit found the recurring trust risks were: empirical claims with
 * no named source ("studies show"), bare round statistics, and quotation marks
 * around Scripture with no reference traveling with them. Live ESV/date lookups
 * are not available at build time, so this does NOT verify — it FLAGS, ranking
 * every published essay by how much of that risk surface it carries, with the
 * offending snippet, so a human (or a scoped agent pass) reviews the right
 * pages instead of all 180. Informational: writes a report, never fails a build.
 *
 * Run: node scripts/scan-citations.mjs   → docs/audit-corpus/CITATION-SCAN.md
 */
import { readFileSync, writeFileSync } from "node:fs";

const data = JSON.parse(readFileSync("client/src/data/content-data.json", "utf8"));
const posts = (data.posts || []).filter(p => p.published && (p.body || "").trim().length >= 600);

// Risk patterns — the audit's top citation-flag categories: empirical claims
// with no named source, and bare statistics stated as fact. (A "loose
// Scripture quote" heuristic was tried and removed: it flagged ordinary
// dialogue and quoted terms far more than genuine unreferenced verses.)
const CHECKS = [
  {
    label: "unsourced-empirical",
    // "studies show", "research suggests", "a survey found", "data shows"…
    re: /\b(studies (?:show|suggest|find|found|say)|research (?:shows?|suggests?|finds?|found)|a (?:study|survey|report|poll) (?:found|showed|says?|by)|surveys? (?:show|found|say)|statistics (?:show|say)|according to (?:a )?(?:study|survey|report|research|data))\b/gi,
  },
  {
    label: "bare-statistic",
    // percentages and "N in N" without an obvious adjacent citation.
    re: /\b(\d{1,3}\s?(?:percent|%)|\d+\s+(?:in|out of)\s+\d+|(?:one|two|three|four|five|six|seven|eight|nine|ten)\s+(?:in|out of)\s+(?:ten|five|four|three|two))\b/gi,
  },
  {
    label: "large-round-number",
    re: /\b\d{1,3}(?:,\d{3})+\b/g, // 40,000 etc.
  },
];

function context(body, idx, len) {
  const s = Math.max(0, idx - 70);
  return body.slice(s, idx + len + 70).replace(/\s+/g, " ").trim();
}

const rows = [];
for (const p of posts) {
  const body = p.body || "";
  const flags = {};
  let total = 0;
  for (const c of CHECKS) {
    const ms = [...body.matchAll(c.re)];
    if (ms.length) {
      flags[c.label] = ms.slice(0, 6).map(m => context(body, m.index, m[0].length));
      total += ms.length;
    }
  }
  if (total) rows.push({ slug: p.slug, title: p.title, total, flags });
}

rows.sort((a, b) => b.total - a.total);

let md = "# Citation Scan — the review worklist\n\n";
md += "> Next-Ten #2, the durable form. Generated by `scripts/scan-citations.mjs`.\n";
md += "> This FLAGS risk patterns (unsourced empirical claims, bare statistics,\n";
md += "> quotation marks around Scripture with no nearby reference); it does not\n";
md += "> verify — live ESV/date lookups are unavailable at build. Review top-down;\n";
md += "> each flag is a claim to source, soften, or cut. Re-run after edits.\n\n";
md += `**${rows.length} of ${posts.length} published essays carry at least one flag.** `;
md += `Total flags: ${rows.reduce((s, r) => s + r.total, 0)}.\n\n`;
for (const r of rows) {
  md += `## ${r.title} \`(${r.slug})\` — ${r.total} flag${r.total > 1 ? "s" : ""}\n\n`;
  for (const [label, snips] of Object.entries(r.flags)) {
    md += `- **${label}:**\n`;
    for (const s of snips) md += `  - …${s}…\n`;
  }
  md += "\n";
}
writeFileSync("docs/audit-corpus/CITATION-SCAN.md", md);
console.log(`Scanned ${posts.length} essays. ${rows.length} carry flags. Report → docs/audit-corpus/CITATION-SCAN.md`);
