#!/usr/bin/env node
/**
 * build-needs-index.mjs — the needs registry manifest.
 *
 * Reads every need in client/public/needs/<slug>.json (full care pages and
 * starter entries alike) and writes client/public/needs/index.json: the
 * fields the /help front door, its search box, the sitemap, and the prerender
 * need, ordered by the need's rank on the demand map (docs/grow/GROW-PROMPT.md,
 * Section 5.3). validate-needs.mjs fails CI when the committed index drifts
 * from what this script would write.
 *
 *   node scripts/build-needs-index.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const DIR = join(ROOT, "client/public/needs");

/** The study guides a need's kit cites, by slug: the guide pages use this to point back to Find Help. */
function guidesOf(n) {
  const k = n.kit || {};
  const hrefs = [...(k.guides || []), ...(k.read || [])].map((x) => (typeof x === "string" ? x : x?.href)).filter(Boolean);
  return [...new Set(hrefs.filter((h) => h.startsWith("/studyguides/")).map((h) => h.slice("/studyguides/".length)))];
}

export function buildNeedsIndex() {
  const needs = readdirSync(DIR)
    .filter((f) => f.endsWith(".json") && f !== "index.json")
    .map((f) => JSON.parse(readFileSync(join(DIR, f), "utf8")))
    .map((n) => ({
      slug: n.slug,
      title: n.title,
      summary: n.summary,
      askedAs: n.askedAs,
      states: n.states,
      sensitivity: n.sensitivity,
      ...(n.crisisTopics ? { crisisTopics: n.crisisTopics } : {}),
      page: n.page === true,
      rank: n.rank,
      ...(n.page === true
        ? { seoTitle: n.seoTitle, description: n.description }
        : { kit: n.kit }),
      ...(n.related ? { related: n.related } : {}),
      ...(guidesOf(n).length ? { guides: guidesOf(n) } : {}),
    }))
    .sort((a, b) => (a.rank ?? 999) - (b.rank ?? 999) || a.slug.localeCompare(b.slug));
  return { note: "Generated by scripts/build-needs-index.mjs. Edit the need files, then rerun.", needs };
}

export function serialize(index) {
  return JSON.stringify(index, null, 2) + "\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const index = buildNeedsIndex();
  writeFileSync(join(DIR, "index.json"), serialize(index));
  console.log(`needs index: ${index.needs.length} needs (${index.needs.filter((n) => n.page).length} care pages)`);
}
