/**
 * topics.mjs — the topic pages (MASTER-PLAN 4): what they are on disk, and the
 * index /topics reads.
 *
 *   client/public/topics/<slug>.json   one hand-built page per question (at most six)
 *   scripts/data/topics-rows.json      the index, in order, in the reader's words
 *   client/public/topics/index.json    generated: the pages (for search, the
 *                                      sitemap, and the prerendered heads) and
 *                                      the rows /topics shows
 *
 * A row opens the one best page for its question: a topic page, a care page,
 * an Honest Answer, a study guide, an essay. A row to an essay that is not
 * public yet names a standIn, which the page opens until the essay is.
 *
 * Read by scripts/build-topics-index.mjs (writes the index), validate-topics.mjs
 * (the gate), and lib/topics-politics.mjs (validate-politics.mjs).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const TOPICS_DIR = "client/public/topics";
export const INDEX_FILE = "client/public/topics/index.json";
export const ROWS_FILE = "scripts/data/topics-rows.json";
/** Three first; at most six until search data argues for more, and raising it is James's call. */
export const MAX_PAGES = 6;

/** What kind of page an address opens, for the row's label and the gate. */
export function kindOf(href) {
  const h = String(href ?? "");
  if (h.startsWith("/topics/")) return "topic";
  if (h.startsWith("/help/") || h === "/help") return "care";
  if (h.startsWith("/answers")) return "answer";
  if (h.startsWith("/writing")) return "essay";
  if (h.startsWith("/studyguides/")) return "study";
  if (h.startsWith("/plans/")) return "plan";
  if (h.startsWith("/theology/") || h.startsWith("/resources/creeds")) return "history";
  if (h.startsWith("/tools/") || h.startsWith("/nation/") || h.startsWith("/disruption/")) return "tool";
  if (h.startsWith("/pathways/")) return "path";
  return "page";
}

/** Every topic page in a folder, sorted by file name: [{ file, slug, data, error? }]. */
export function readTopicPages(dir = path.join(ROOT, TOPICS_DIR)) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".json") && f !== "index.json")
    .sort()
    .map((file) => {
      const slug = file.replace(/\.json$/, "");
      try {
        return { file, slug, data: JSON.parse(fs.readFileSync(path.join(dir, file), "utf8")) };
      } catch (err) {
        return { file, slug, data: null, error: err.message };
      }
    });
}

export function readRows(file = path.join(ROOT, ROWS_FILE)) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

const text = (x) => (typeof x === "string" ? x.trim() : "");

/**
 * The index from the pages and the ordered rows. Returns { index, problems };
 * problems are the things that stop it being built at all (a row naming a
 * topic that has no page, a page no row lists). The gate checks the rest.
 */
export function buildTopicsIndex(pages, rowsSource) {
  const problems = [];
  const bySlug = new Map();
  for (const p of pages) {
    if (!p.data) {
      problems.push(`${p.file}: not readable JSON (${p.error})`);
      continue;
    }
    bySlug.set(p.slug, p.data);
  }
  const listed = new Set();
  const rows = [];
  for (const [i, r] of (Array.isArray(rowsSource?.rows) ? rowsSource.rows : []).entries()) {
    if (r && typeof r.topic === "string") {
      const t = bySlug.get(r.topic);
      if (!t) {
        problems.push(`rows[${i}]: no topic page "${r.topic}" in ${TOPICS_DIR}`);
        continue;
      }
      if (listed.has(r.topic)) problems.push(`rows[${i}]: the topic "${r.topic}" is listed twice`);
      listed.add(r.topic);
      rows.push({ askedAs: text(t.title), href: `/topics/${r.topic}`, kind: "topic", line: text(t.description) });
      continue;
    }
    const row = { askedAs: text(r?.askedAs), href: text(r?.href), kind: kindOf(r?.href), line: text(r?.line) };
    if (r?.standIn) Object.assign(row, { standIn: text(r.standIn), standInKind: kindOf(r.standIn) });
    if (r?.also) row.also = { href: text(r.also.href), label: text(r.also.label), line: text(r.also.line) };
    rows.push(row);
  }
  for (const slug of bySlug.keys()) if (!listed.has(slug)) problems.push(`${slug}.json: no row in ${ROWS_FILE} lists this topic`);
  const order = [...listed];
  const index = {
    about:
      "Generated by scripts/build-topics-index.mjs from client/public/topics/<slug>.json and scripts/data/topics-rows.json. Do not edit by hand. pages: the topic pages (search, sitemap, prerendered heads). rows: the questions /topics lists, in order, each opening the one best page.",
    pages: order.map((slug) => {
      const t = bySlug.get(slug);
      return {
        slug,
        title: text(t.title),
        description: text(t.description),
        blurb: text(t.description),
        askedAs: Array.isArray(t.askedAs) ? t.askedAs.map(text).filter(Boolean) : [],
        href: `/topics/${slug}`,
      };
    }),
    rows,
  };
  return { index, problems };
}

export function renderTopicsIndex(index) {
  return `${JSON.stringify(index, null, 2)}\n`;
}

/**
 * Every reader-facing string in a topic page, with where it sits, for the
 * style checks: [path, text]. Addresses, slugs, refs, and dates are left out.
 */
export function topicStrings(page) {
  const out = [];
  const SKIP = new Set(["slug", "href", "devotion", "updated", "ref", "folds", "reviewed", "politics", "sensitive", "crisis", "standIn"]);
  const walk = (v, where) => {
    if (typeof v === "string") out.push([where, v]);
    else if (Array.isArray(v)) v.forEach((x, i) => walk(x, `${where}[${i}]`));
    else if (v && typeof v === "object") for (const [k, x] of Object.entries(v)) if (!SKIP.has(k)) walk(x, where ? `${where}.${k}` : k);
  };
  walk(page, "");
  return out;
}

export const words = (s) => String(s ?? "").trim().split(/\s+/).filter(Boolean).length;
